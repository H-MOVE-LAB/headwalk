def extract_subject_and_tp(filename: str) -> Tuple[str | None, str | None]:
    """
    Extract subject code and timepoint from filename.
    Returns (subject_code, timepoint e.g. 'F2') or (None, None) on failure.
    """
    m = _SUBJECT_RE.search(filename)
    if not m:
        return None, None
    subj = m.group(1).upper()
    tp = m.group(2).upper()
    return subj, tp


def age_to_bin(age_val: float) -> str:
    """
    Place a numeric age into the AGE_LABELS categories.
    """
    try:
        a = float(age_val)
    except Exception:
        return "Unknown"
    idx = np.digitize([a], AGE_BINS, right=False)[0] - 1
    if idx < 0 or idx >= len(AGE_LABELS):
        return "Unknown"
    return AGE_LABELS[idx]


def safe_unique_list(vals) -> List:
    """Return unique list preserving order, excluding nan/None/empty."""
    seen = set()
    out = []
    for v in list(vals):
        if pd.isna(v):
            continue
        if v not in seen:
            seen.add(v)
            out.append(v)
    return out


def pairwise_mwu_with_bonferroni(groups: Dict[str, np.ndarray]) -> pd.DataFrame:
    """
    For dictionary group_name -> values array, compute pairwise Mann-Whitney U tests,
    apply Bonferroni correction for multiple comparisons (multiply p by n_comparisons).
    Returns DataFrame with columns: group1, group2, p_uncorrected, p_bonf, stat.
    """
    names = list(groups.keys())
    n = len(names)
    comparisons = []
    for a, b in combinations(names, 2):
        x = groups[a]
        y = groups[b]
        # remove NaNs
        x = x[np.isfinite(x)]
        y = y[np.isfinite(y)]
        if len(x) == 0 or len(y) == 0:
            stat, p = np.nan, np.nan
        else:
            # use two-sided
            stat, p = stats.mannwhitneyu(x, y, alternative="two-sided")
        comparisons.append({"g1": a, "g2": b, "stat": float(stat) if not np.isnan(stat) else np.nan, "p_uncorrected": float(p) if not np.isnan(p) else np.nan})

    # Bonferroni correction
    m = len(comparisons)
    for c in comparisons:
        if not np.isnan(c["p_uncorrected"]):
            c["p_bonf"] = min(1.0, c["p_uncorrected"] * m)
        else:
            c["p_bonf"] = np.nan

    return pd.DataFrame(comparisons)


