def group_summary_stats(df: pd.DataFrame, group_col: str, metric_cols: List[str]) -> pd.DataFrame:
    """
    Return a DataFrame with group means/std/count for metric_cols.
    """
    agg = {}
    for m in metric_cols:
        agg[m + "_mean"] = (m, "mean")
        agg[m + "_std"] = (m, "std")
        agg[m + "_n"] = (m, "count")
    # perform grouped aggregation
    grouped = df.groupby(group_col).agg(**{k: pd.NamedAgg(column=v[0], aggfunc=v[1]) for k, v in agg.items()})
    grouped = grouped.reset_index()
    return grouped


