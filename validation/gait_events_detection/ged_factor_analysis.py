def analyze_factor(
    metrics_df: pd.DataFrame,
    *,
    factor_col: str,
    factor_name: str,
    cohort_filter: str | None = None,
    event_type: str = "IC",
    palette: Dict[str, str] | None = None,
):
    """
    High-level wrapper: filter by cohort & event_type, compute group stats,
    draw plot, run tests, and save outputs.
    """
    df_sub = metrics_df.copy()
    if cohort_filter is not None:
        df_sub = df_sub[df_sub["cohort"] == cohort_filter].copy()

    df_sub = df_sub[df_sub["event_type"] == event_type].copy()
    if df_sub.empty:
        print(f"[SKIP] No rows for event_type={event_type} and cohort={cohort_filter}")
        return

    # group summary
    group_stats = group_summary_stats(df_sub, factor_col, ["f1", "mae"])
    out_prefix = f"{factor_name}_{event_type}" + (f"_{cohort_filter}" if cohort_filter else "")
    # save group stats
    csv_stats = PLOTS_OUTDIR / f"{out_prefix}_group_stats.csv"
    group_stats.to_csv(csv_stats, index=False)

    # plot
    png_path = PLOTS_OUTDIR / f"{out_prefix}_boxplots.png"
    plot_group_boxplots(df_sub, factor_col, event_type, png_path, title_prefix=factor_name, palette=palette)

    # tests (for both F1 and MAE)
    omnibus_f1, posthoc_f1 = run_stat_tests(df_sub, factor_col, "f1")
    omnibus_mae, posthoc_mae = run_stat_tests(df_sub, factor_col, "mae")

    # Build results dataframes
    omnibus_df = pd.DataFrame([{"metric": "f1", **omnibus_f1}, {"metric": "mae", **omnibus_mae}])
    omnibus_df.to_csv(PLOTS_OUTDIR / f"{out_prefix}_omnibus.csv", index=False)

    if posthoc_f1 is not None:
        posthoc_f1.to_csv(PLOTS_OUTDIR / f"{out_prefix}_posthoc_f1.csv", index=False)
    if posthoc_mae is not None:
        posthoc_mae.to_csv(PLOTS_OUTDIR / f"{out_prefix}_posthoc_mae.csv", index=False)

    print(f"[SAVED] {csv_stats}, {png_path}, omnibus & posthoc CSVs.")


