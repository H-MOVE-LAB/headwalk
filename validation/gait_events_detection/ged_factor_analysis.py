def run_stat_tests(df: pd.DataFrame, group_col: str, metric_col: str) -> Tuple[Dict[str, Any], pd.DataFrame | None]:
    """
    Run Kruskal-Wallis omnibus on groups in group_col for metric_col.
    If >2 groups, also do pairwise Mann-Whitney U with Bonferroni correction.
    Returns:
      - omnibus_result: dict with H, p, n_groups, group_counts
      - posthoc_df: pairwise comparisons df (or None if not applicable)
    """
    # prepare groups
    groups = {}
    for name, sub in df.groupby(group_col):
        arr = sub[metric_col].dropna().astype(float).to_numpy()
        if len(arr) > 0:
            groups[name] = arr

    group_names = list(groups.keys())
    counts = {k: len(groups[k]) for k in group_names}
    omnibus = {"H": np.nan, "p": np.nan, "n_groups": len(group_names), "counts": counts}

    if len(group_names) < 2:
        return omnibus, None

    # Kruskal-Wallis
    try:
        stats_args = [groups[k] for k in group_names]
        H, p = stats.kruskal(*stats_args)
        omnibus["H"] = float(H)
        omnibus["p"] = float(p)
    except Exception as e:
        omnibus["H"] = np.nan
        omnibus["p"] = np.nan

    posthoc_df = None
    if len(group_names) > 2:
        posthoc_df = pairwise_mwu_with_bonferroni(groups)
    elif len(group_names) == 2:
        # just compute the single MWU and return
        a, b = group_names
        x = groups[a]; y = groups[b]
        stat, pval = stats.mannwhitneyu(x, y, alternative="two-sided")
        posthoc_df = pd.DataFrame([{"g1": a, "g2": b, "stat": float(stat), "p_uncorrected": float(pval), "p_bonf": float(min(1.0, pval))}])

    return omnibus, posthoc_df


